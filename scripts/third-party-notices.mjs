#!/usr/bin/env node
// Writes src/assets/notices/third-party.txt: the name, version, licence and licence text of every
// component Aji ships, for the About page (M5 design 5.4). Rust crates are the normal dependencies
// of the `aji` package, reached from `cargo metadata` (dev and build dependencies do not ship);
// npm packages are the production dependencies from `pnpm licenses list --prod`. Aji's own
// workspace crates are left out.
//
// Each distinct licence file is printed once, after the list of packages that carry it, so the
// file stays small enough to bundle.
//
//   node scripts/third-party-notices.mjs           regenerate the file
//   node scripts/third-party-notices.mjs --check   exit 1 when the committed file is stale

import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'src', 'assets', 'notices', 'third-party.txt');
const LICENCE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/i;

function run(command, args) {
  return execFileSync(command, args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 256 << 20 });
}

/** The licence files at the top of a package folder, sorted by name, with normalised line ends. */
function licenceTexts(folder) {
  let names;
  try {
    names = readdirSync(folder);
  } catch {
    return [];
  }
  return names
    .filter((name) => LICENCE_FILE.test(name) && statSync(path.join(folder, name)).isFile())
    .sort()
    .map((name) => readFileSync(path.join(folder, name), 'utf8').replace(/\r\n?/g, '\n').trim());
}

function rustPackages() {
  const metadata = JSON.parse(run('cargo', ['metadata', '--format-version', '1', '--locked']));
  const byId = new Map(metadata.packages.map((p) => [p.id, p]));
  const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
  const workspace = new Set(metadata.workspace_members);
  const start = metadata.packages.find((p) => p.name === 'aji' && workspace.has(p.id));
  if (!start) throw new Error('package aji not found in cargo metadata');

  const seen = new Set([start.id]);
  const queue = [start.id];
  while (queue.length > 0) {
    const node = nodes.get(queue.shift());
    for (const dep of node?.deps ?? []) {
      const normal = dep.dep_kinds.some((kind) => kind.kind === null);
      if (normal && !seen.has(dep.pkg)) {
        seen.add(dep.pkg);
        queue.push(dep.pkg);
      }
    }
  }

  return [...seen]
    .filter((id) => !workspace.has(id))
    .map((id) => byId.get(id))
    .map((p) => ({
      name: p.name,
      version: p.version,
      licence: p.license ?? (p.license_file ? `see ${p.license_file}` : 'unknown'),
      texts: licenceTexts(path.dirname(p.manifest_path)),
    }));
}

function npmPackages() {
  const report = JSON.parse(run('pnpm', ['licenses', 'list', '--prod', '--json']));
  const packages = [];
  for (const [licence, entries] of Object.entries(report)) {
    for (const entry of entries) {
      entry.versions.forEach((version, index) => {
        packages.push({
          name: entry.name,
          version,
          licence,
          texts: licenceTexts(entry.paths[index] ?? entry.paths[0]),
        });
      });
    }
  }
  return packages;
}

function render(title, packages) {
  packages.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  // Each distinct licence file is printed once, after the packages that carry it.
  const groups = new Map();
  for (const pkg of packages) {
    const texts = pkg.texts.length > 0 ? pkg.texts : [`(no licence file; ${pkg.licence})`];
    for (const text of texts) {
      if (!groups.has(text)) groups.set(text, []);
      groups.get(text).push(pkg);
    }
  }
  const lines = [`${title} (${packages.length})`, ''];
  for (const pkg of packages) lines.push(`  ${pkg.name} ${pkg.version}  ${pkg.licence}`);
  lines.push('');
  for (const [text, members] of groups) {
    lines.push('-'.repeat(72));
    lines.push(members.map((p) => `${p.name} ${p.version}`).join(', '));
    lines.push('');
    lines.push(text);
    lines.push('');
  }
  return lines.join('\n');
}

function generate() {
  return [
    'Open-source components in Aji',
    '',
    'Generated by scripts/third-party-notices.mjs from the Rust and npm dependency graphs.',
    '',
    '='.repeat(72),
    render('Rust crates', rustPackages()),
    '='.repeat(72),
    render('npm packages', npmPackages()),
  ]
    .join('\n')
    .replace(/[ \t]+$/gm, '')
    .trimEnd()
    .concat('\n');
}

const text = generate();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    // Missing counts as stale.
  }
  if (current !== text) {
    console.error(
      `${path.relative(ROOT, OUTPUT)} is stale; run node scripts/third-party-notices.mjs`,
    );
    process.exit(1);
  }
  console.log('third-party notices are up to date');
} else {
  writeFileSync(OUTPUT, text);
  console.log(`wrote ${path.relative(ROOT, OUTPUT)} (${text.length} characters)`);
}
