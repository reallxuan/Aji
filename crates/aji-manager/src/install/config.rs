//! KataGo's config files for an engine and network pair (design 5.5): Aji's keys first, then
//! the manifest's overrides.

use std::collections::BTreeMap;
use std::fmt::Write;

use super::{BenchmarkPlan, InstallRoot};

const HEADER: &str = "# Generated by Aji. It is rewritten when the engine is set up again.\n";

/// The analysis engine's config. No `numSearchThreads`: KataGo refuses it together with
/// `numSearchThreadsPerAnalysisThread` (findings 4a). Every key is one the analysis engine
/// reads, because it warns about unused keys (findings 4b). No logging key is needed
/// (findings 4c).
pub fn analysis_config(threads: u32, overrides: &BTreeMap<String, String>) -> String {
    render(
        &[
            ("homeDataDir", InstallRoot::katago_home_rel().to_string()),
            ("numAnalysisThreads", "1".into()),
            ("numSearchThreadsPerAnalysisThread", threads.to_string()),
            ("nnMaxBatchSize", threads.to_string()),
            ("nnCacheSizePowerOfTwo", "20".into()),
            ("nnMutexPoolSizePowerOfTwo", "14".into()),
        ],
        overrides,
    )
}

/// `benchmark`'s config: `numSearchThreads` is required, at the plan's first count; `-t`
/// then sweeps the counts (findings 4a).
pub fn benchmark_config(plan: &BenchmarkPlan, overrides: &BTreeMap<String, String>) -> String {
    let first = plan.threads.first().copied().unwrap_or(1);
    render(
        &[
            ("homeDataDir", InstallRoot::katago_home_rel().to_string()),
            ("numSearchThreads", first.to_string()),
        ],
        overrides,
    )
}

/// The header, Aji's keys, then the overrides. An override of a key Aji writes replaces Aji's
/// line, so each key appears once. The manifest checks override keys and values
/// (`parse_manifest`): a key is letters, digits and `_`, a value has no line break or `#`.
fn render(aji: &[(&str, String)], overrides: &BTreeMap<String, String>) -> String {
    let mut text = String::from(HEADER);
    for (key, value) in aji {
        if !overrides.contains_key(*key) {
            let _ = writeln!(text, "{key} = {value}");
        }
    }
    for (key, value) in overrides {
        let _ = writeln!(text, "{key} = {value}");
    }
    text
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::install::benchmark_plan;
    use crate::manifest::Backend;

    fn directml() -> BTreeMap<String, String> {
        BTreeMap::from([("onnxProvider".to_string(), "directml".to_string())])
    }

    #[test]
    fn the_analysis_config_has_the_threads_and_the_overrides() {
        let config = analysis_config(8, &directml());
        assert!(config.starts_with(HEADER), "{config}");
        for line in [
            "homeDataDir = katago-home\n",
            "numAnalysisThreads = 1\n",
            "numSearchThreadsPerAnalysisThread = 8\n",
            "nnMaxBatchSize = 8\n",
            "nnCacheSizePowerOfTwo = 20\n",
            "nnMutexPoolSizePowerOfTwo = 14\n",
        ] {
            let at = config
                .find(line)
                .unwrap_or_else(|| panic!("{line:?} in {config}"));
            assert!(
                at < config.find("onnxProvider = directml\n").unwrap(),
                "{line:?}"
            );
        }
        assert!(config.ends_with("onnxProvider = directml\n"), "{config}");
        assert!(!config.contains("numSearchThreads ="), "{config}");
        assert!(!config.contains("log"), "no logging keys: {config}");
    }

    #[test]
    fn the_benchmark_config_carries_the_manifest_overrides() {
        let config = benchmark_config(&benchmark_plan(Backend::Metal, 10), &directml());
        assert!(config.starts_with(HEADER), "{config}");
        assert!(config.contains("homeDataDir = katago-home\n"), "{config}");
        assert!(config.contains("numSearchThreads = 6\n"), "{config}");
        assert!(config.ends_with("onnxProvider = directml\n"), "{config}");
        assert!(!config.contains("numSearchThreadsPerAnalysisThread"));
    }

    /// KataGo reads each key once, so a manifest override of a key Aji writes replaces
    /// Aji's line instead of repeating the key.
    #[test]
    fn an_override_replaces_an_aji_key() {
        let overrides = BTreeMap::from([("nnMaxBatchSize".to_string(), "32".to_string())]);
        let config = analysis_config(8, &overrides);
        assert_eq!(config.matches("nnMaxBatchSize").count(), 1, "{config}");
        assert!(config.ends_with("nnMaxBatchSize = 32\n"), "{config}");
        let overrides = BTreeMap::from([("numSearchThreads".to_string(), "4".to_string())]);
        let config = benchmark_config(&benchmark_plan(Backend::Cuda, 10), &overrides);
        assert_eq!(config.matches("numSearchThreads").count(), 1, "{config}");
    }
}
